<?php
require_once("../media/PHPMailer_SMTP/PHPMailerAutoload.php");

class email {
	function set_smtp_parameters(){
		$smtp_parameters				= array();
		$smtp_parameters['host'] 		= '192.168.3.254';
		$smtp_parameters['encryption'] 	= 'none';
		$smtp_parameters['username'] 	= 'issinfoservice';
		$smtp_parameters['password'] 	= 'pmi1234';
		$smtp_parameters['port'] 		= '25';
		return $smtp_parameters;
	}

	function send_email($to, $from, $cc, $subject, $body,$attachment) {
		$body = str_replace("\n","<br>",$body);
		// require_once("../includes/PHPMailer/class.phpmailer.php");
		$mail = new PHPMailer();

		$smtp_parameters = $this->set_smtp_parameters();
		$mail->IsSMTP();
		$mail->IsHTML(true);
		// $mail->SMTPDebug = 1; 
		$mail->Host 		= $smtp_parameters['host'];
		$mail->SMTPAuth 	= true;
		$mail->SMTPSecure 	= $smtp_parameters['encryption'];
		$mail->Username 	= $smtp_parameters['username'];
		$mail->Password 	= $smtp_parameters['password'];
		$mail->Port 		= $smtp_parameters['port'];	
		
		if($to != '') {
			$to = explode(",",$to);
			for($i=0; $i<sizeof($to);$i++) {
				$mail->AddAddress($to[$i]);	
			}
		}
		if($cc != '') {
			$cc = explode(",",$cc);
			for($i=0; $i<sizeof($cc);$i++) {
				$mail->AddCC($cc[$i]);	
			}
		}
        $body .= "<br><br><i>For more info, please log-in to your Rapid account. Go to http://rapid/ <br>";
		$body .= "This E-mail is automatically generated by Die-set Maintenance Cycle Monitoring System (DMCMS). <br>";
		$body .= "Don't reply to this e-mail, this is only a notification created by the system, Thank you!</i>";
        $body .= "<br><br>Notice of Disclaimer:<br>
                    This message (including any attachments) contains confidential information intended for a specific individual and purpose, and is protected by law. If you are not the intended recipient, you should delete this message. Any disclosure,copying, or distribution of this message, or the taking of any action based on it, is strictly prohibited.
";
		$mail->From = $from;
		$mail->FromName = "Die-set Maintenance Cycle Monitoring System";
		// $mail->AddBCC("ronfern@pricon.ph");
		$mail->AddBCC("ralatie@pricon.ph");
		$mail->Subject = $subject;
		$mail->Body= $body;
		
        if($attachment != '') {
            $mail->AddAttachment($attachment);
        }
        
		if(!$mail->Send())
		{
		   $msg = "Message could not be sent.";
		   $msg .= "Mailer Error: " . $mail->ErrorInfo ."\n";
		   exit;
		} else {
			$msg = "Message has been sent!";
		}
		return $msg; 
	}
}
?>